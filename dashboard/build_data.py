"""Collect the result CSVs the dashboard shows into dashboard/data.js (window.DATA).

    cd endsem && .venv/bin/python ../dashboard/build_data.py

Each table is stored as {cols: [...], rows: [[...], ...]} to keep the file small; app.js expands it.
Re-run after re-running any experiment, then commit data.js.
"""
import json
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
END = os.path.join(HERE, "..", "endsem")
R = os.path.join(END, "results")

MN = {"mixtral": "Mixtral-8x7B", "grok1": "Grok-1", "llama4_maverick": "Llama-4 Maverick", "deepseekR1": "DeepSeek-R1"}
LK = {"PCIe4": "PCIe 4.0", "PCIe5": "PCIe 5.0", "C2C-450": "C2C-450", "C2C-900": "C2C-900"}


def pack(df, digits=4):
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].round(digits)
    rows = [[None if (isinstance(v, float) and v != v) else v for v in r] for r in df.itertuples(index=False)]
    return {"cols": list(df.columns), "rows": rows}


def ladder():
    d = pd.read_csv(os.path.join(R, "e3_ablation", "ablation.csv"))
    d["cache"] = (d.ratio_setting * 100).round().astype(int).astype(str) + "%"
    k = ["model", "batch", "link", "cache"]
    base = d[d.rung == "1 on-demand, no cache"].set_index(k).token_latency_ms.rename("od")
    lro = d[d.rung == "LRU + miss overlap (no prediction)"].set_index(k).token_latency_ms.rename("lo")
    d = d.join(base, on=k).join(lro, on=k)
    d["speedup"] = d.od / d.token_latency_ms
    d["vs_lru_overlap"] = d.lo / d.token_latency_ms
    d["model"], d["link"], d["batch"] = d.model.map(MN), d.link.map(LK), d.batch.astype(str)
    cols = k + ["rung", "token_latency_ms", "speedup", "vs_lru_overlap", "hit_rate", "stall_fraction", "GB_per_token",
                "wasted_GB_per_token", "prefetch_accuracy", "expert_wait_ms", "energy_J_per_token",
                "transfer_J_per_token", "dynamic_J_per_token", "background_J_per_token"]
    return pack(d[cols])


def accuracy():
    PN = {"prev_token": "previous token", "temporal": "temporal", "cross": "cross-layer", "popularity": "popularity",
          "equal_topk": "3 predictors, equal", "chooser_topk": "3 predictors + chooser",
          "full": "ours (full, adaptive budget)", "oracle": "oracle"}
    a = pd.read_csv(os.path.join(R, "e2_predictor_accuracy", "summary.csv"))
    a["predictor"], a["model"], a["traces"] = a.predictor.map(PN), a.model.map(MN), "public"
    e = pd.read_csv(os.path.join(R, "e7_hybrid_calibrated", "accuracy.csv"))
    e = e[e.context == 1024].copy()
    e["predictor"] = e.predictor.replace({"ID-only (ours)": "ours, ID-only (H100 tokens)",
                                          "hidden-state + our budget": "hidden-state + our budget (H100)"})
    e["model"], e["traces"] = "Mixtral-8x7B", "h100"
    cols = ["model", "batch", "predictor", "traces", "distance", "overlap", "recall", "precision", "fullcov", "budget", "union"]
    out = pd.concat([a[cols], e[cols]])
    out["batch"] = out.batch.astype(str)
    return pack(out)


def context():
    c = pd.read_csv(os.path.join(R, "e6_context", "context_with_speedup.csv"))
    c = c[(c.cache != "0%") | (c.policy == "on-demand")].copy()
    c["model"], c["link"], c["batch"] = c.model.map(MN), c.link.map(LK), c.batch.astype(str)
    return pack(c[["model", "batch", "link", "cache", "context", "policy", "token_latency_ms", "speedup", "hit_rate",
                   "energy_J_per_token"]])


def bonus():
    b = pd.read_csv(os.path.join(R, "bonus_llmsim", "policies.csv"))
    b["model"], b["link"], b["batch"] = b.model.map(MN), b.link.map(LK), b.batch.astype(str)
    return pack(b[["model", "batch", "link", "routing", "policy", "token_latency_ms", "speedup", "GB_per_token", "hit_rate"]])


def h100_validation():
    g = pd.read_csv(os.path.join(END, "gpu", "results", "compare.csv"))
    g["batch"] = g.batch.astype(str)
    return pack(g[["run_id", "batch", "ctx", "cache_ratio", "config", "spec_item", "real_token_latency_ms",
                   "sim_cal_token_latency_ms", "sim_default_token_latency_ms", "real_hit_rate", "sim_cal_hit_rate"]])


def h100_speed():
    s = pd.read_csv(os.path.join(R, "e7_hybrid_calibrated", "policies.csv"))
    s = s[(s.context == 1024) & (s.link == "PCIe5")].copy()
    s["batch"] = s.batch.astype(str)
    return pack(s[["batch", "policy", "token_latency_ms", "speedup", "hit_rate"]])


def main():
    data = dict(ladder=ladder(), accuracy=accuracy(), context=context(), bonus=bonus(),
                h100_validation=h100_validation(), h100_speed=h100_speed())
    path = os.path.join(HERE, "data.js")
    with open(path, "w") as f:
        f.write("// Generated by build_data.py from endsem/results and endsem/gpu/results. Do not edit by hand.\n")
        f.write("window.DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    print("wrote", path, os.path.getsize(path), "bytes;", {k: len(v["rows"]) for k, v in data.items()})


if __name__ == "__main__":
    main()
